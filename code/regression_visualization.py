import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

plt.rcParams['font.sans-serif'] = ['SimHei']
plt.rcParams['axes.unicode_minus'] = False


# ============================================================
# 1. 读取数据
# ============================================================

df = pd.read_excel(
    "SURF_regression_data_2.xlsx",
    engine="openpyxl"
)

# 只保留交易时间内的事件
intraday_df = df[
    df["event_type"] == "INTRADAY"
].copy()


# ============================================================
# 2. 三个收益窗口
# ============================================================

horizon_list = [
    "return_t+5",
    "return_t+10",
    "return_t+20"
]

title_list = [
    "未来5分钟收益",
    "未来10分钟收益",
    "未来20分钟收益"
]


# ============================================================
# 3. 创建 1×3 子图
# ============================================================

fig, axes = plt.subplots(
    1,
    3,
    figsize=(15, 5),
    dpi=120
)


# ============================================================
# 4. 绘制散点 + OLS 回归线
# ============================================================

for ax, horizon, title in zip(
    axes,
    horizon_list,
    title_list
):

    sns.regplot(
        x="z_face_a",
        y=horizon,
        data=intraday_df,
        ax=ax,

        scatter_kws={
            "s": 25,
            "alpha": 0.7,
            "color": "#2c7bb6"
        },

        line_kws={
            "color": "#d7191c",
            "linewidth": 2
        },

        ci=95
    )

    ax.set_title(
        title,
        fontsize=11,
        pad=8
    )

    ax.set_xlabel(
        "标准化面部情绪得分",
        fontsize=9
    )

    ax.set_ylabel(
        "前瞻收益",
        fontsize=9
    )

    ax.grid(
        alpha=0.3,
        linestyle="--"
    )


# ============================================================
# 5. 总标题
# ============================================================

plt.suptitle(
    "不同时间窗口：面部情绪 vs 沪深300前瞻收益",
    fontsize=14,
    y=1.02
)


# ============================================================
# 6. 调整布局
# ============================================================

plt.tight_layout()


# ============================================================
# 7. 保存图片
# ============================================================

plt.savefig(
    "三窗口散点回归汇总.png",
    dpi=300,
    bbox_inches="tight"
)


# ============================================================
# 8. 显示
# ============================================================

plt.show()
